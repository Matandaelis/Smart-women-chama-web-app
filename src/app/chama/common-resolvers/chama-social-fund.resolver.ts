import { Injectable, inject } from '@angular/core';
import { Resolve } from '@angular/router';
import { Observable } from 'rxjs';
import { ChamaService } from '../chama.service';
import { SocialFund } from '../models';

@Injectable({ providedIn: 'root' })
export class ChamaSocialFundResolver implements Resolve<SocialFund | null> {
  private chamaService = inject(ChamaService);

  resolve(): Observable<SocialFund | null> {
    return this.chamaService.getSocialFund();
  }
}
